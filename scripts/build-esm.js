#!/usr/bin/env node
'use strict';

/**
 * Build `esm/index.mjs`, the ES module entry of this package, from the
 * CommonJS sources in `src/`.
 *
 * The sources stay CommonJS so the server requires them directly. A browser
 * build (Vite) needs ES modules and will not rewrite CommonJS outside
 * node_modules, so this wraps every source file, unchanged, in a function
 * and wires them together with a tiny module table. The output has no
 * imports and no dependencies; its named exports are exactly the CommonJS
 * entry's keys. `__tests__/esm.test.js` fails when the committed file is not
 * a fresh build, so run `node scripts/build-esm.js` after changing `src/`.
 *
 *   node scripts/build-esm.js          write esm/index.mjs
 *   node scripts/build-esm.js --check  exit 1 if it is stale
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'esm', 'index.mjs');

function render() {
  const files = fs.readdirSync(SRC).filter(name => name.endsWith('.js')).sort();
  const modules = files.map(name => {
    const source = fs.readFileSync(path.join(SRC, name), 'utf8').trimEnd();
    return `  './${name.slice(0, -3)}': function (module, exports, require) {\n${source}\n  }`;
  });
  const names = Object.keys(require(SRC));
  return [
    '// Generated by scripts/build-esm.js from src/. Do not edit by hand.',
    'const sources = {',
    modules.join(',\n'),
    '};',
    'const cache = {};',
    'function load(name) {',
    '  const key = name.replace(/\\.js$/, \'\');',
    '  if (cache[key]) return cache[key].exports;',
    '  const module = { exports: {} };',
    '  cache[key] = module;',
    '  sources[key](module, module.exports, load);',
    '  return module.exports;',
    '}',
    'const core = load(\'./index\');',
    'export default core;',
    `export const {\n  ${names.join(',\n  ')}\n} = core;`,
    ''
  ].join('\n');
}

function main(args) {
  const fresh = render();
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (args.includes('--check')) {
    if (current !== fresh) {
      console.error('esm/index.mjs is stale: run node scripts/build-esm.js');
      return 1;
    }
    return 0;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, fresh);
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { render, main, OUT };
